"""Sūrat al-Kahf for the reader: the Madani mushaf pages (293-304) line by line in the King Fahd Complex page fonts,
and each verse's Uthmani text with The Clear Quran beside it. Nothing is retyped: every word, glyph code, page and line
comes from tools/src/quran-18-mushaf.json (api.quran.com), the translation from tools/src/quran-18-translation.json
(only footnote markers removed), and the bismillah from the Fātiḥah's own source (quran-1.json, 1:1).
Output: web/js/kahf.js (window.KAHF)."""
import io, json, os, re

ROOT = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(ROOT, 'src')
OUT = os.path.join(ROOT, '..', 'web', 'js', 'kahf.js')

m = json.load(io.open(os.path.join(SRC, 'quran-18-mushaf.json'), encoding='utf-8'))
tr = json.load(io.open(os.path.join(SRC, 'quran-18-translation.json'), encoding='utf-8'))
fat = json.load(io.open(os.path.join(SRC, 'quran-1.json'), encoding='utf-8'))['verses']
bism = [v for v in fat if v['verse_key'] == '1:1'][0]['text_uthmani'].strip()


def clean(t):
    t = re.sub(r'<sup[^>]*>.*?</sup>', '', t)          # footnote markers, as tools/fetch_clearquran.py
    t = re.sub(r'<[^>]+>', '', t).replace('\xa0', ' ')
    return re.sub(r'\s+', ' ', t).strip()


pages = {}
verses = []
for v in m['verses']:
    verses.append({'n': v['n'], 'p': v['page'], 'ar': v['text'].strip(), 'en': clean(tr[v['key']])})
    for w in v['words']:
        pg = pages.setdefault(w['p'], {})
        ln = pg.setdefault(w['l'], [])
        ln.append([w['c'], v['n'], 1 if w['k'] == 'end' else 0])

out = {
    'surah': 18, 'name': 'Al-Kahf', 'ar': 'الكهف', 'ayahs': len(verses),
    'bismillah': bism,
    # 18:75 opens the sixteenth juzʾ
    'juz': {'1': 15, '75': 16},
    'pages': [{'p': p, 'lines': [{'l': l, 'w': pages[p][l]} for l in sorted(pages[p])]} for p in sorted(pages)],
    'verses': verses
}
js = '/* Generated by tools/build_kahf.py from the verified sources in tools/src. Do not edit. */\nwindow.KAHF=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n'
io.open(OUT, 'w', encoding='utf-8', newline='\n').write(js)
print('kahf: %d verses on %d pages, %d KB' % (len(verses), len(pages), len(js.encode('utf-8')) // 1024))
